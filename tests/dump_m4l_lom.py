"""Dump Live's object model as Max for Live sees it (dev tool, not a unit test).

Max devices reach Live through ``LiveAPI`` / ``live.object``, which shows the documented Live
Object Model -- not quite what the Remote Script's Python sees (``tests/dump_live_api.py``).
This asks a running LiveBridge Engine device (``lom_dump``): its ``context.js`` walks the object
model from ``live_app``, ``live_set`` and ``this_device`` (every object type once, devices once
per class) and reads each object's ``info``: properties, functions and children.

Writes ``docs/LIVE_M4L_LOM_<version>.json`` and ``.md``; the Markdown also lists, per type, what
Python has that Max cannot reach (and the reverse) when ``docs/LIVE_API_DUMP_<version>.json``
exists for the same Live version.

Usage (Live running, a LiveBridge Engine on any track; the more device kinds in the set, the
more device classes the dump covers)::

    python tests/dump_m4l_lom.py [--track NAME]
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "mcp_server"))

from livebridge_mcp import engine  # noqa: E402

DOCS = os.path.join(ROOT, "docs")


def _python_classes(version):
    path = os.path.join(DOCS, "LIVE_API_DUMP_%s.json" % version)
    try:
        with open(path, encoding="utf-8") as handle:
            classes = json.load(handle).get("classes") or {}
    except (OSError, ValueError):
        return None, None
    by_name = {}
    for name, cls in classes.items():
        by_name.setdefault(name.rsplit(".", 1)[-1], cls)
    return by_name, os.path.basename(path)


def _python_members(cls):
    props, funcs = set(), set()
    for name, member in (cls.get("members") or {}).items():
        if name.startswith("_") or name.endswith("_listener") or \
                name.endswith("_has_listener"):
            continue
        (props if member.get("kind") == "property" else funcs).add(name)
    return props, funcs


def compare(info, cls):
    """``(python only, max only)`` member names of one type."""
    props, funcs = _python_members(cls)
    max_props = {p[0] for p in info.get("properties") or []} | \
        {c[0] for c in info.get("children") or []}
    max_funcs = set(info.get("functions") or [])
    python_only = sorted((props - max_props - max_funcs) | (funcs - max_funcs - max_props))
    max_only = sorted((max_props | max_funcs) - props - funcs)
    return python_only, max_only


def markdown(dump):
    version = dump.get("live_version") or "unknown"
    classes, source = _python_classes(version)
    out = ["# Max for Live object model — Live %s" % version, "",
           "Generated by `tests/dump_m4l_lom.py` from a running LiveBridge Engine (LiveAPI "
           "`info` of every object type reached from `live_app`, `live_set` and `this_device`; "
           "devices once per class). LiveAPI lists what each object has (a return track has "
           "no `arm`), so every type shows the members of all its objects together; one seen "
           "only once can still lack members other objects of it have.", "",
           "- Max %s, Node %s, Engine %s; %d types from %d objects looked at." % (
               dump.get("max_version"), dump.get("node_version"), dump.get("engine_version"),
               len(dump.get("types") or {}), dump.get("objects_looked_at") or 0)]
    if source:
        out.append("- \"Python only\" / \"Max only\" compare with `%s` (members of the Python "
                   "class of the same name; listeners left out)." % source)
    out.append("")
    for key in sorted(dump.get("types") or {}):
        info = dump["types"][key]
        out += ["## %s" % key, "", "Example path: `%s`%s" % (
            info.get("path"), " (members merged from %d objects)" % info["objects"]
            if (info.get("objects") or 1) > 1 else "")]
        if info.get("description"):
            out += ["", info["description"]]
        if info.get("properties"):
            out += ["", "Properties: " + ", ".join(("`%s` %s" % (p[0], p[1])).strip()
                                                   for p in sorted(info["properties"]))]
        if info.get("functions"):
            out += ["", "Functions: " + ", ".join("`%s`" % f
                                                  for f in sorted(set(info["functions"])))]
        if info.get("children"):
            out += ["", "Children: " + ", ".join(
                "`%s` %s%s" % (c[0], c[1], " (list)" if c[2] else "")
                for c in info["children"])]
        cls = (classes or {}).get(str(info.get("type")))
        if cls:
            python_only, max_only = compare(info, cls)
            if python_only:
                out += ["", "Python only: " + ", ".join("`%s`" % n for n in python_only)]
            if max_only:
                out += ["", "Max only: " + ", ".join("`%s`" % n for n in max_only)]
        out.append("")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--track", help="the Engine on this track (default: the first found)")
    args = parser.parse_args(argv)
    found = engine.devices()
    if not found:
        print("No LiveBridge Engine answers: put one on a track in Live and try again.")
        return 1
    try:
        device = engine.choose(found, args.track)
    except engine.EngineError as exc:
        print(exc)
        return 1
    parts = [int(p) if p.isdigit() else 0 for p in str(device.get("version") or "0").split(".")]
    if parts[:3] < [1, 6, 1]:
        print("The Engine is %s; the dump needs 1.6.1+ (reinstall the devices, then replace "
              "the Engine in the set)." % device.get("version"))
        return 1
    try:
        dump = engine.request(device, "lom_dump", timeout=90.0)
    except engine.EngineError as exc:
        print("The dump failed: %s" % exc)
        return 1
    version = dump.get("live_version") or "unknown"
    base = os.path.join(DOCS, "LIVE_M4L_LOM_%s" % version)
    with open(base + ".json", "w", encoding="utf-8") as handle:
        json.dump(dump, handle, indent=1, sort_keys=True)
    with open(base + ".md", "w", encoding="utf-8") as handle:
        handle.write(markdown(dump))
    print("wrote %s.json and .md (%d types)" % (base, len(dump.get("types") or {})))
    return 0


if __name__ == "__main__":
    sys.exit(main())
